"""Small JSON state file (.local_ai/state.json) and .env helpers."""
import json
import secrets

from . import paths


def load_state():
    try:
        return json.loads(paths.STATE_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def save_state(state):
    paths.STATE_DIR.mkdir(parents=True, exist_ok=True)
    tmp = paths.STATE_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=2), encoding="utf-8")
    tmp.replace(paths.STATE_FILE)


# ---- .env -----------------------------------------------------------------

ENV_DEFAULTS = {
    # Where the dashboard and the AI server listen. 127.0.0.1 = this computer
    # only; 0.0.0.0 = also reachable from the network (launcher flag --host).
    "BIND_HOST": "127.0.0.1",
    # MySQL and Qdrant are published separately: nothing outside this computer
    # needs them, so they stay on 127.0.0.1 unless --expose-databases is used.
    "DB_BIND_HOST": "127.0.0.1",
    "MYSQL_DATABASE": "veritas_lens",
    "MYSQL_USER": "veritas_lens",
    "MYSQL_PASSWORD": None,        # None -> random secret generated on first run
    "MYSQL_ROOT_PASSWORD": None,
    "MYSQL_PORT": "3306",
    "QDRANT_PORT": "6333",
    "QDRANT_GRPC_PORT": "6334",
    "LLAMA_SWAP_PORT": "8080",
    # The nginx proxy in front of the dashboard: 80 is the default web port, so
    # the dashboard opens without a port number (launcher flag --no-proxy skips it).
    "HTTP_PORT": "80",
    "LLAMA_CTX_SIZE": "16384",
}


def read_env():
    values = {}
    try:
        lines = paths.ENV_FILE.read_text(encoding="utf-8").splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def set_env_values(updates):
    """Update or append keys in .env, keeping comments and unrelated lines."""
    try:
        lines = paths.ENV_FILE.read_text(encoding="utf-8").splitlines()
    except OSError:
        lines = ["# Local settings for the self-hosted setup. Generated by the launcher;",
                 "# safe to edit. Never commit this file."]
    remaining = dict(updates)
    for i, line in enumerate(lines):
        key = line.split("=", 1)[0].strip()
        if "=" in line and not line.lstrip().startswith("#") and key in remaining:
            lines[i] = f"{key}={remaining.pop(key)}"
    lines += [f"{k}={v}" for k, v in remaining.items()]
    paths.ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def ensure_env():
    """Create .env on first run (random DB passwords) and fill in missing keys."""
    current = read_env()
    missing = {}
    for key, default in ENV_DEFAULTS.items():
        if key not in current:
            missing[key] = default if default is not None else secrets.token_urlsafe(18)
    if missing:
        set_env_values(missing)
    return read_env()

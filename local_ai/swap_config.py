"""Generate the llama-swap config (.local_ai/llama-swap.yaml).

The app should always call the stable aliases, never a concrete model name:
    "chat"       -> whichever Gemma model was selected for this machine
    "embedding"  -> EmbeddingGemma (768-dim vectors, for Qdrant)
Both sit in one llama-swap group with swap: false, so they stay loaded side
by side instead of unloading each other on every request.
"""
import hashlib

from . import paths
from .runtime import lib_env, server_supports


def _q(path):
    """Quote a path for llama-swap's shell-style cmd parsing (forward slashes
    avoid backslash-escape problems on Windows)."""
    return '"' + str(path).replace("\\", "/") + '"'


def _yaml_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _cmd_block(lines, indent=6):
    pad = " " * indent
    return "|\n" + "\n".join(pad + line for line in lines)


def build(server, backend, chat_model, chat_path, mmproj_path, placement,
          embed_model, embed_path, env):
    ctx = int(env.get("LLAMA_CTX_SIZE", 16384))
    parallel = int(env.get("LLAMA_PARALLEL", 1))
    # Recent llama.cpp builds auto-fit layers/context to free memory (--fit,
    # on by default). Older builds need explicit GPU layer flags.
    has_fit = server_supports(server, "--fit")
    gpu_flags = []
    if backend != "cpu" and not has_fit:
        gpu_flags = ["--n-gpu-layers 999"]
        if placement.startswith("gpu+cpu") and server_supports(server, "--n-cpu-moe"):
            gpu_flags.append("--n-cpu-moe 999")

    chat_cmd = [
        _q(server),
        "--host 127.0.0.1 --port ${PORT}",
        f"--model {_q(chat_path)}",
        *( [f"--mmproj {_q(mmproj_path)}"] if mmproj_path else [] ),
        f"--ctx-size {ctx}",
        f"--parallel {parallel}",
        "--jinja",
        *gpu_flags,
    ]
    if env.get("LLAMA_EXTRA_ARGS"):
        chat_cmd.append(env["LLAMA_EXTRA_ARGS"])

    emb_ctx = int(embed_model.get("ctx", 2048))
    embed_cmd = [
        _q(server),
        "--host 127.0.0.1 --port ${PORT}",
        f"--model {_q(embed_path)}",
        "--embedding",
        # Non-causal embedding models must fit a whole input in one batch.
        f"--ctx-size {emb_ctx} --batch-size {emb_ctx} --ubatch-size {emb_ctx}",
        *(["--n-gpu-layers 999"] if backend != "cpu" and not has_fit else []),
    ]

    env_lines = ""
    extra_env = lib_env(server.parent)
    if extra_env:
        env_lines = "    env:\n" + "\n".join(
            f"      - {_yaml_str(f'{k}={v}')}" for k, v in extra_env.items()) + "\n"

    chat_id, embed_id = chat_model["id"], embed_model["id"]
    return f"""# Generated by the launcher (python -m local_ai). Do not edit by hand:
# change .env or local_ai/ and re-run the launcher instead.
# Selected for this machine: {chat_model['id']} ({placement}), backend: {backend}
healthCheckTimeout: 600
logLevel: info
startPort: 10001
globalTTL: 0
includeAliasesInList: true

models:
  {_yaml_str(chat_id)}:
    name: {_yaml_str(chat_id + " (chat)")}
    cmd: {_cmd_block(chat_cmd)}
{env_lines}    aliases:
      - "chat"
    metadata:
      vision: {"true" if mmproj_path else "false"}

  {_yaml_str(embed_id)}:
    name: {_yaml_str(embed_id + " (embeddings)")}
    cmd: {_cmd_block(embed_cmd)}
{env_lines}    aliases:
      - "embedding"
    metadata:
      dimensions: {embed_model.get("dimensions", 768)}

# Top-level `groups` (rather than routing.router.settings.groups) so older
# llama-swap versions accept the config too; newer ones still support it.
groups:
  "local-ai":
    swap: false
    exclusive: true
    members:
      - {_yaml_str(chat_id)}
      - {_yaml_str(embed_id)}

hooks:
  on_startup:
    preload:
      - {_yaml_str(chat_id)}
      - {_yaml_str(embed_id)}
"""


def write(text):
    """Write the config; returns its hash (used to detect when a restart is needed)."""
    paths.SWAP_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    paths.SWAP_CONFIG.write_text(text, encoding="utf-8", newline="\n")
    return hashlib.sha256(text.encode()).hexdigest()[:16]
